import assert from 'node:assert/strict';
import { readFileSync,readdirSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
const source=readFileSync(new URL('../analytics/ga4-v1.js',import.meta.url),'utf8');
const consent=readFileSync(new URL('../analytics/ga4-v1-consent.js',import.meta.url),'utf8');
const storage=new Map(),scripts=[],listeners={};
const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const w={localStorage,location:{origin:'https://tramipago.com.ar',pathname:'/index.html',search:'?dni=SECRETO',hash:'#/seguimiento?codigo=MUYPRIVADO'},addEventListener:(n,fn)=>{listeners[n]=fn;}};
const document={referrer:'https://www.google.com/search?q=PRIVADO',head:{appendChild:s=>scripts.push(s)},createElement:()=>({})};
runInNewContext(source,{window:w,document,Date,URL});
const api=w.TramiPagoGA4;
assert.equal(scripts.length,0);
assert.equal(api.start('G-J1JRESTCK5',{consentGranted:false}),false);
assert.equal(scripts.length,0);
assert.equal(api.markTestBrowser(),true);
assert.equal(api.isTestBrowser(),true);
assert.equal(api.start('G-J1JRESTCK5',{consentGranted:true}),false);
assert.equal(scripts.length,0,'Browser de prueba excluido antes de cargar Google');
assert.equal(w.dataLayer,undefined,'Sin solicitud a Google ni eventos de prueba');
assert.equal(api.unmarkTestBrowser(),true);
assert.equal(api.isTestBrowser(),false);
assert.equal(api.start('G-J1JRESTCK5',{consentGranted:true}),true);
assert.equal(scripts.length,1);
scripts[0].onload();
const views=w.dataLayer.filter(x=>x[0]==='event'&&x[1]==='page_view');
assert.equal(views.length,1);
assert.equal(views[0][2].page_location,'https://tramipago.com.ar/index.html#/seguimiento');
assert.equal(views[0][2].page_referrer,'https://www.google.com/');
assert.equal(views[0][2].debug_mode,false);
assert.equal(w.dataLayer.find(x=>x[0]==='config')[2].send_page_view,false);
assert.ok(!JSON.stringify(w.dataLayer).includes('SECRETO'));
assert.ok(!JSON.stringify(w.dataLayer).includes('MUYPRIVADO'));
assert.ok(!JSON.stringify(w.dataLayer).includes('PRIVADO'));
api.revokeConsent();listeners.hashchange();
assert.equal(w.dataLayer.filter(x=>x[0]==='event').length,1);
assert.match(consent,/localStorage\.setItem\(key,v\)/);
assert.match(consent,/api\.start\(cfg\.measurementId,\{consentGranted:true\}\)/);
assert.match(consent,/api\.revokeConsent\(\)/);
assert.match(consent,/window\.location\.reload\(\)/);
const htmls=readdirSync(new URL('..',import.meta.url)).filter(x=>x.endsWith('.html'));
assert.equal(htmls.length,39);
for(const f of htmls){
 const h=readFileSync(new URL('../'+f,import.meta.url),'utf8');
 assert.match(h,/analytics\/ga4-v1-consent\.js/);
 assert.match(h,/analytics\/ga4-v1-consent\.css/);
 assert.match(h,/www\.googletagmanager\.com/);
}
console.log('PASS: GA4 bloqueado sin consentimiento y excluye navegador de prueba, sanitización URL, revocación, 39 HTML públicos');
