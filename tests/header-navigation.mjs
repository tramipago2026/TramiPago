import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>readFileSync(resolve(root,name),'utf8');
const js=read('header-fijo-20260917.js');
const css=read('header-fijo-20260917.css');
const app=read('app.js');
const services=read('extra-families.js');
const search=read('catalog-search.js');
const index=read('index.html');
const config=read('services.js');
let legal=null,style=null,hashHandler=null;
const home={href:'#/',attributes:{},querySelector:()=>null,insertAdjacentHTML(){this.hasIcon=true;},setAttribute(k,v){this.attributes[k]=v;},removeAttribute(k){delete this.attributes[k];}};
const tracking={href:'#/seguimiento',attributes:{},setAttribute(k,v){this.attributes[k]=v;},removeAttribute(k){delete this.attributes[k];}};
const help={dataset:{action:'whatsapp'}};
const brand={href:'#/',insertAdjacentElement(_position,el){legal=el;}};
const nav={querySelector(selector){return ({'.nav-home':home,'.nav-tracking':tracking,'.nav-help':help})[selector]||null;}};
const row={classList:{add(value){this.value=value;}},querySelector(selector){return ({'.brand':brand,'.main-nav':nav})[selector]||null;}};
const header={classList:{add(value){this.value=value;}},querySelector:()=>row};
const document={readyState:'complete',head:{appendChild(el){style=el;}},querySelector(selector){return ({'.site-header':header,'.site-header .nav-home':home,'.site-header .nav-tracking':tracking})[selector]||null;},getElementById(id){return id==='tramipago-header-legal'?legal:id==='tramipago-header-fixed-20260917'?style:null;},createElement(tag){return {tag,attributes:{},setAttribute(k,v){this.attributes[k]=v;},removeAttribute(k){delete this.attributes[k];}};}};
const location={hash:'#/'};
const window={TRAMI_FAMILIES:[{id:'atencion-abogado'}],addEventListener(name,handler){if(name==='hashchange')hashHandler=handler;}};
runInNewContext(js,{document,window,location});
assert.equal(row.classList.value,'header-featured','Se aplica distribución nueva');
assert.equal(brand.href,'#/','Logo abre Inicio');
assert.equal(home.href,'#/','Inicio abre portada');
assert.equal(tracking.href,'#/seguimiento','Estado abre seguimiento');
assert.equal(help.dataset.action,'whatsapp','Ayuda conserva acción de WhatsApp');
assert.equal(legal.href,'#/familia/atencion-abogado','Consulta legal abre familia de formularios');
assert.equal(home.attributes['aria-current'],'page','Inicio activo en portada');
assert.ok(home.hasIcon,'Inicio conserva icono');
assert.ok(style.href.includes('header-fijo-20260917.css'),'Se carga hoja de estilos');
assert.ok(legal.innerHTML.includes('ART · Accidentes · Sucesiones'),'Texto aprobado');
location.hash='#/seguimiento';hashHandler();
assert.equal(tracking.attributes['aria-current'],'page','Se identifica estado activo');
location.hash='#/familia/atencion-abogado';hashHandler();
assert.equal(legal.attributes['aria-current'],'page','Se identifica atención legal activa');
assert.ok(services.includes('id:"atencion-abogado"'),'Existe familia legal');
assert.ok(app.includes('if (hash === "#/seguimiento")')&&app.includes('id="tracking-code"'),'Estado tiene formulario de código');
assert.ok(app.includes('const whatsapp = event.target.closest(')&&app.includes('openWhatsApp()'),'Ayuda abre WhatsApp mediante gestor existente');
assert.ok(config.includes('whatsappNumber:'),'Número configurado');
assert.ok(index.includes('href="#/"')&&index.includes('href="#/seguimiento"'),'Enlaces del HTML conservados');
assert.ok(search.includes('import("./header-fijo-20260917.js'),'Cabecera integrada en página');
assert.ok(css.includes('grid-template-columns:116px')&&css.includes('@media(max-width:590px)'),'Cabecera horizontal y adaptación móvil');
assert.ok(existsSync(resolve(root,'assets','header-consulta-legal-20260917.svg')),'Ilustración disponible');
